"""Generate yuan.tokyo's SVG and React mark from Hina Mincho outlines.

Build-time only: pip install fonttools, then run with a HinaMincho-Regular.ttf path.
Source: https://github.com/google/fonts/tree/main/ofl/hinamincho
License: src/minato-design/fonts/hinamincho-OFL.txt (SIL OFL).
"""
from pathlib import Path
from sys import argv
from random import Random
from math import hypot, ceil, sin
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen
from fontTools.misc.transform import Transform

font = TTFont(argv[1])
glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
def outline_cell(char, col, row):
    glyph = glyphs[cmap[ord(char)]]
    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    scale = 64 / font['head'].unitsPerEm
    cx, cy = 22 + col * 92 + 40, 14 + row * 80 + 40
    if char == '。':
        # Vertical punctuation occupies the upper-right of its full-width cell.
        cx, cy = 22 + col * 92 + 62, 14 + row * 80 + 18
    tx, ty = cx - scale * (x0 + x1) / 2, cy + scale * (y0 + y1) / 2
    pen = SVGPathPen(glyphs, ntos=lambda n: format(n, '.3f').rstrip('0').rstrip('.'))
    glyph.draw(TransformPen(pen, Transform(scale, 0, 0, -scale, tx, ty)))
    return pen.getCommands()

# Read top to bottom, right column first: ユアン / 。東京.
paths = [outline_cell(char, col, row) for char, col, row in
         [('。', 0, 0), ('東', 0, 1), ('京', 0, 2), ('ユ', 1, 0), ('ア', 1, 1), ('ン', 1, 2)]]

# Dry, worn printing: actual vector edges and transparent gaps, not a raster filter.
# Seeded so regeneration preserves the exact same imperfections.
rng = Random(2406)

def worn_rule(x1, y1, x2, y2, width=1.6, guide=False, breaks=()):
    length = hypot(x2 - x1, y2 - y1)
    dx, dy = (x2 - x1) / length, (y2 - y1) / length
    nx, ny = -dy, dx
    # Structural rules are whole ribbons, interrupted only at authored damage.
    # Cell guides retain the intentional dashes of the writing-paper reference.
    intervals = []
    position = 0.0
    if guide:
        while position < length:
            end = min(position + rng.uniform(2.5, 4.5), length)
            intervals.append((position, end))
            position = end + rng.uniform(2.4, 3.8)
    else:
        for gap_start, gap_end in breaks:
            intervals.append((position, gap_start))
            position = gap_end
        intervals.append((position, length))
    polygons = []
    phase = rng.uniform(0, 6.28)
    for start, end in intervals:
        count = max(2, ceil((end - start) / 2.4))
        top, bottom = [], []
        for i in range(count + 1):
            t = start + (end - start) * i / count
            wobble = .17 * sin(t / 14 + phase) + rng.uniform(-.06, .06)
            # Wear nibbles at the edges without cutting the ribbon into dashes.
            half_a = width * rng.uniform(.40, .60)
            half_b = width * rng.uniform(.40, .60)
            if rng.random() < .10:
                half_a *= .30
            if rng.random() < .10:
                half_b *= .30
            for edge, offset in [(top, wobble + half_a), (bottom, wobble - half_b)]:
                edge.append((x1 + dx * t + nx * offset, y1 + dy * t + ny * offset))
        points = top + bottom[::-1]
        polygons.append('M' + 'L'.join(f'{x:.2f},{y:.2f}' for x, y in points) + 'Z')
    return ''.join(polygons)

# Two larger tears, three tiny ink losses, and several completely unbroken rules.
# Positions are distances along each rule; damage stays away from intersections.
vertical_damage = {
    14: [(133, 142)],
    22: [],
    102: [(57, 64)],
    114: [(193, 194.2)],
    194: [],
    202: [(42, 42.8), (211, 211.6)],
}
frame = ''.join(worn_rule(x, 14, x, 254, breaks=gaps) for x, gaps in vertical_damage.items())
frame += worn_rule(14, 14, 202, 14) + worn_rule(14, 254, 202, 254)
guides = ''.join(worn_rule(left, y, right, y, width=1, guide=True)
                 for y in [94, 174] for left, right in [(22, 102), (114, 194)])
svg = '''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 216 268" width="216" height="268" role="img" aria-labelledby="title desc" color="#253237">
  <title id="title">yuan.tokyo</title>
  <desc id="desc">A worn Japanese writing grid: 。, 東, 京 in the left column; ユ, ア, ン in the right. Hina Mincho letterforms, converted to outlines.</desc>
  <!-- Glyph source: Hina Mincho, SIL OFL; see src/minato-design/fonts/hinamincho-OFL.txt. -->
  <g id="mark" fill="currentColor">
'''
svg += f'    <path d="{frame}" />\n'
svg += f'    <path d="{guides}" opacity=".7"/>\n'
svg += '\n'.join(f'    <path d="{path}"/>' for path in paths)
svg += '\n  </g>\n</svg>\n'
Path('public/yuan-tokyo.svg').write_text(svg)

component = '''// Generated by scripts/build-logo.py; Hina Mincho outlines, SIL OFL.
import { useId } from 'react';
import type { SVGProps } from 'react';

export type LogoProps = Omit<SVGProps<SVGSVGElement>, 'children'> & { decorative?: boolean };

/** Site identity, intentionally separate from the reusable Minato component library. */
export function Logo({ decorative = false, className = '', ...props }: LogoProps) {
  const titleId = useId();
  return <svg width="54" height="67" {...props} viewBox="0 0 216 268" className={`site-logo ${className}`}
    role={decorative ? undefined : 'img'} aria-hidden={decorative || undefined}
    aria-labelledby={decorative ? undefined : titleId} focusable="false">
    {!decorative && <title id={titleId}>yuan.tokyo — ユアン・東京</title>}
    <g fill="currentColor">
'''
component += f'      <path d="{frame}"  />\n'
component += f'      <path d="{guides}" opacity=".7" />\n'
component += '\n'.join(f'      <path d="{path}" />' for path in paths)
component += '\n    </g>\n  </svg>;\n}\n'
Path('src/components/Logo.tsx').write_text(component)
print(f'Generated six outlined glyphs; standalone SVG is {len(svg.encode())} bytes.')

# Alternate: two rows, surname 袁 above the period in the right column.
alt_paths = [outline_cell(char, col, row) for char, col, row in
             [('東', 0, 0), ('京', 0, 1), ('袁', 1, 0), ('。', 1, 1)]]
rng = Random(2406)
alt_damage = {
    14: [(105, 114)],
    22: [],
    102: [(34, 41)],
    114: [(125, 126.2)],
    194: [],
    202: [(42, 42.8)],
}
alt_frame = ''.join(worn_rule(x, 14, x, 174, breaks=gaps) for x, gaps in alt_damage.items())
alt_frame += worn_rule(14, 14, 202, 14) + worn_rule(14, 174, 202, 174)
alt_guides = ''.join(worn_rule(left, 94, right, 94, width=1, guide=True)
                     for left, right in [(22, 102), (114, 194)])
alt_svg = svg.replace('0 0 216 268', '0 0 216 188').replace('height="268"', 'height="188"')
alt_svg = alt_svg.replace('。, 東, 京 in the left column; ユ, ア, ン in the right.',
                          '東, 京 in the left column; 袁, 。 in the right.')
alt_svg = alt_svg.replace(frame, alt_frame).replace(guides, alt_guides)
alt_svg = alt_svg.replace('\n'.join(f'    <path d="{path}"/>' for path in paths),
                          '\n'.join(f'    <path d="{path}"/>' for path in alt_paths))
Path('public/yuan-tokyo-alt.svg').write_text(alt_svg)
alt_component = component.replace('LogoProps', 'LogoAltProps').replace('function Logo(', 'function LogoAlt(')
alt_component = alt_component.replace('0 0 216 268', '0 0 216 188').replace('height="67"', 'height="47"')
alt_component = alt_component.replace('ユアン・東京', '袁・東京')
alt_component = alt_component.replace(frame, alt_frame).replace(guides, alt_guides)
alt_component = alt_component.replace('\n'.join(f'      <path d="{path}" />' for path in paths),
                                      '\n'.join(f'      <path d="{path}" />' for path in alt_paths))
Path('src/components/LogoAlt.tsx').write_text(alt_component)
print(f'Generated alternate four-cell surname mark; {len(alt_svg.encode())} bytes.')
